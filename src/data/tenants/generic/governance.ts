export function applyGenericEnrichment(pack: TenantPack): TenantPack {
  const next = structuredClone(pack) as TenantPack
  if (!next.decisions?.length) next.decisions = structuredClone(genericDecisions)
  if (!next.auditHistory?.length) next.auditHistory = structuredClone(genericAuditHistory)
  return next
}

