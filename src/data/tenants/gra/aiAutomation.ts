function base(id: string, name: string, description: string, ownerId = 'person-chief-architect') {
  return {
    id,
    tenantId: T,
    name,
    description,
    status: 'active' as const,
    ownerId,
    createdAt: now,
    updatedAt: now,
    dataQuality: 'high' as const,
    sourceRefs: ['gra-ai-seed-v1'],
    tags: ['ai', 'synthetic'],
    isSynthetic: true,
  }
}

function gov(
  overall: AiSolution['governanceStatus'],
  detail: NonNullable<AiSolution['governanceDetail']>,
): Pick<AiSolution, 'governanceStatus' | 'governanceDetail'> {
  return { governanceStatus: overall, governanceDetail: detail }
}

function rails(partial: Partial<NonNullable<AiSolution['guardrails']>>): NonNullable<AiSolution['guardrails']> {
  return {
    approvedUseCase: 'Defined',
    allowedActions: 'Defined',
    prohibitedActions: 'Partial',
    approvedData: 'Defined',
    humanApproval: 'Defined',
    escalation: 'Partial',
    outputReview: 'Defined',
    monitoring: 'Partial',
    ...partial,
  }
}

type SolSeed = Omit<
  AiSolution,
  'tenantId' | 'createdAt' | 'updatedAt' | 'dataQuality' | 'sourceRefs' | 'tags' | 'status' | 'ownerId'
> & { ownerId?: string }

function sol(seed: SolSeed): AiSolution {
  return {
    ...base(seed.id, seed.name, seed.description, seed.ownerId),
    ...seed,
  }
}

