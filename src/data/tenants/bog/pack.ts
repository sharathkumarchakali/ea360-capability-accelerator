const T = 'tenant-bog'

function base(
  id: string,
  name: string,
  description: string,
  ownerId: string,
  status: TenantPack['capabilities'][number]['status'] = 'active',
  tags: string[] = [],
) {
  return entityBase(T, id, name, description, ownerId, status, tags, ['bog-seed-v1'])
}

function cap(
  id: string,
  name: string,
  description: string,
  ownerId: string,
  level: 1 | 2,
  domain: string,
  opts: {
    parentId?: string
    maturityCurrent: number
    maturityTarget: number
    strategicImportance: number
    riskScore: number
    investmentPriority: number
    strategicObjectiveIds: string[]
    tags?: string[]
  },
) {
  return {
    ...base(id, name, description, ownerId, 'active', opts.tags ?? []),
    level,
    parentId: opts.parentId,
    domain,
    maturityCurrent: opts.maturityCurrent,
    maturityTarget: opts.maturityTarget,
    strategicImportance: opts.strategicImportance,
    riskScore: opts.riskScore,
    investmentPriority: opts.investmentPriority,
    strategicObjectiveIds: opts.strategicObjectiveIds,
  }
}

