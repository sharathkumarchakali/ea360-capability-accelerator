/**
 * Optional enrichment hook — pack already bakes workflow fields; this merges
 * decisions/audit if a caller starts from a lean pack clone.
 */
export function applyBogEnrichment(pack: TenantPack): TenantPack {
  const next = structuredClone(pack) as TenantPack
  if (!next.decisions?.length) next.decisions = structuredClone(bogDecisions)
  if (!next.auditHistory?.length) next.auditHistory = structuredClone(bogAuditHistory)
  return next
}

